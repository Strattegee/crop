"""Turns the legal documents in docs/legal/*.md into apps/web/lib/legal/documents.ts (run after editing them).
The markdown files are the source; the web app shows them at /legal."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = [
    ('privacy', 'Privacy Policy', 'How CROP handles personal information.'),
    ('worker-notice', 'Worker privacy notice', 'A short notice for people who use CROP through their employer.'),
    ('terms', 'Subscription Agreement', 'The terms for businesses that subscribe to CROP.'),
    ('data-processing', 'Data Processing Agreement', 'How we handle personal information on a business\'s behalf.'),
    ('acceptable-use', 'Acceptable Use Policy', 'What everyone using CROP agrees not to do.'),
    ('schedules', 'Service levels, security and data', 'Service levels, security commitments, data lifecycle and the subprocessor register.'),
]
VERSION = 'Version 0.1 (draft), 24 October 2026'
out = []
for slug, title, summary in DOCS:
    text = open(os.path.join(HERE, f'{slug}.md'), encoding='utf-8').read()
    lines = text.split('\n')
    if lines and lines[0].startswith('# '):  # the pack's own heading; the page uses `title`
        text = '\n'.join(lines[1:]).lstrip('\n')
    out.append({'slug': slug, 'title': title, 'summary': summary, 'body': text})
dest = os.path.join(HERE, '..', '..', 'apps', 'web', 'lib', 'legal', 'documents.ts')
os.makedirs(os.path.dirname(dest), exist_ok=True)
with open(dest, 'w', encoding='utf-8') as f:
    f.write('// Generated by docs/legal/build.py from docs/legal/*.md. Edit those files, then run the script.\n\n')
    f.write('export type LegalDoc = { slug: string; title: string; summary: string; body: string };\n\n')
    f.write(f'export const LEGAL_VERSION = {json.dumps(VERSION)};\n\n')
    f.write('export const LEGAL_DOCS: LegalDoc[] = ' + json.dumps(out, ensure_ascii=False, indent=2) + ';\n')
print('wrote', dest)
